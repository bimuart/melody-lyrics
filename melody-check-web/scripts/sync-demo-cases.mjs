import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const webRoot = path.join(__dirname, "..");
const src = path.join(webRoot, "..", "demo-cases");
const dest = path.join(webRoot, "public", "demo-cases");
const generatedTs = path.join(webRoot, "src", "constants", "demoCaseFiles.generated.ts");

if (!fs.existsSync(src)) {
  console.error("Source not found:", src);
  process.exit(1);
}
fs.mkdirSync(dest, { recursive: true });
const fileNames = fs
  .readdirSync(src)
  .filter((name) => name.toLowerCase().endsWith(".md"))
  .sort((a, b) => a.localeCompare(b, "en", { numeric: true }));

for (const name of fileNames) {
  const from = path.join(src, name);
  if (fs.statSync(from).isFile()) {
    fs.copyFileSync(from, path.join(dest, name));
  }
}

const generatedContent = `// Auto-generated by scripts/sync-demo-cases.mjs
export const DEMO_CASE_FILES = ${JSON.stringify(fileNames.map((name) => `demo-cases/${name}`), null, 2)} as const;
`;
fs.writeFileSync(generatedTs, generatedContent, "utf8");

console.log("Synced demo-cases ->", dest);
